// Lowercase mapping to uppercase fallback with lowercase specific touch
const LOWERCASE_MAP: Record<string, string> = {
  'a': 'A', 'b': 'B', 'c': 'C', 'd': 'D', 'e': 'E', 'f': 'F', 'g': 'G',
  'h': 'H', 'i': 'I', 'j': 'J', 'k': 'K', 'l': 'L', 'm': 'M', 'n': 'N',
  'o': 'O', 'p': 'P', 'q': 'Q', 'r': 'R', 's': 'S', 't': 'T', 'u': 'U',
  'v': 'V', 'w': 'W', 'x': 'X', 'y': 'Y', 'z': 'Z',
  'ç': 'Ç', 'ğ': 'Ğ', 'ı': 'I', 'ö': 'Ö', 'ş': 'Ş', 'ü': 'Ü'
};

/**
 * Returns a 2D matrix (height x width) of 1s and 0s for a given character in 5x7 font.
 */
export function get5x7CharMatrix(ch: string): number[][] {
  const target = FONT_5X7[ch] || FONT_5X7[LOWERCASE_MAP[ch]] || FONT_5X7['?'] || FONT_5X7[' '];
  return target;
}

export function get7x9CharMatrix(ch: string): number[][] {
  if (FONT_7X9[ch]) return FONT_7X9[ch];
  if (FONT_7X9[LOWERCASE_MAP[ch]]) return FONT_7X9[LOWERCASE_MAP[ch]];
  // Fallback: upscale 5x7 to 7x9
  const m5 = get5x7CharMatrix(ch);
  const res: number[][] = Array.from({ length: 9 }, () => Array(7).fill(0));
  for (let r = 0; r < 7; r++) {
    for (let c = 0; c < 5; c++) {
      if (m5[r][c] === 1) {
        res[r + 1][c + 1] = 1;
      }
    }
  }
  return res;
}

/**
 * Renders text onto a 1-Bit pixel grid buffer.
 * @param text The text string to render
 * @param fontType '5x7' or '7x9'
 * @param scale Integer scale (1 = native, 2 = 2x, 3 = 3x, 4 = 4x)
 * @param inverted If true, text is inverted (white on black box)
 */
export function renderBitmapText(
  text: string,
  scale: number = 1,
  fontType: '5x7' | '7x9' = '5x7',
  inverted: boolean = false
): { width: number; height: number; pixels: number[][] } {
  const is7x9 = fontType === '7x9';
  const baseCharWidth = is7x9 ? 7 : 5;
  const baseCharHeight = is7x9 ? 9 : 7;
  const charSpacing = 1;
  const pad = inverted ? 2 : 0;

  const charW = baseCharWidth * scale;
  const charH = baseCharHeight * scale;
  const spaceW = charSpacing * scale;
  const padPx = pad * scale;

  const totalWidth = text.length * (charW + spaceW) - spaceW + padPx * 2;
  const totalHeight = charH + padPx * 2;

  // Initialize grid
  const initialVal = inverted ? 1 : 0;
  const textVal = inverted ? 0 : 1;
  const pixels: number[][] = Array.from({ length: totalHeight }, () => Array(totalWidth).fill(initialVal));

  for (let cIdx = 0; cIdx < text.length; cIdx++) {
    const char = text[cIdx];
    const matrix = is7x9 ? get7x9CharMatrix(char) : get5x7CharMatrix(char);
    const startX = padPx + cIdx * (charW + spaceW);

    for (let r = 0; r < baseCharHeight; r++) {
      for (let c = 0; c < baseCharWidth; c++) {
        if (matrix[r] && matrix[r][c] === 1) {
          for (let sy = 0; sy < scale; sy++) {
            for (let sx = 0; sx < scale; sx++) {
              const py = padPx + r * scale + sy;
              const px = startX + c * scale + sx;
              if (py < totalHeight && px < totalWidth) {
                pixels[py][px] = textVal;
              }
            }
          }
        }
      }
    }
  }

  return { width: Math.max(1, totalWidth), height: Math.max(1, totalHeight), pixels };
}
